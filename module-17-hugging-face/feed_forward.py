import torch
import torch.nn as nn
import torch.nn.functional as F


class FeedForwardNetwork(nn.Module):
    """
    Feed-Forward Network (FFN) - двухслойная нейросеть для трансформера.

    Архитектура (как в математической части главы 6):
        1. Linear 1: Проекция из embed_dim в ff_dim (расширение)
        2. ReLU: Функция активации (нелинейность)
        3. Linear 2: Проекция из ff_dim обратно в embed_dim (сжатие)

    Args:
        embed_dim: Размерность входных/выходных векторов
                   В нашем примере: 16
                   В GPT-3 (175B): 12288

        ff_dim: Размерность скрытого слоя (промежуточного представления)
                В нашем примере: 64 (4× embed_dim)
                В GPT-3 (175B): 49152 (4× embed_dim)

    Почему ff_dim больше embed_dim?
        • Больше пространства для обработки информации
        • Модель может выучить более сложные представления
        • ReLU отсекает часть нейронов, поэтому нужно «про запас»

    Важно: В этом классе реализуется ТОЛЬКО FFN.
    Объединение с Attention будет в главе 7 (TransformerBlock).
    """

    def __init__(self, embed_dim, ff_dim=None):
        super().__init__()

        # ============================================================
        # СОХРАНЯЕМ ПАРАМЕТРЫ
        # ============================================================
        self.embed_dim = embed_dim

        # Если ff_dim не указан, используем стандартное соотношение 4×
        # Это распространённая практика в трансформерах
        if ff_dim is None:
            ff_dim = 4 * embed_dim

        self.ff_dim = ff_dim

        # ============================================================
        # ЛИНЕЙНЫЙ СЛОЙ 1 (W_1)
        # ============================================================
        # Математика: Intermediate = X @ W_1
        #             W_1 имеет размер [embed_dim, ff_dim]
        #
        # В коде: nn.Linear автоматически создаёт матрицу весов
        #         и обрабатывает умножение
        #
        # Пример для embed_dim=16, ff_dim=64:
        #   W_1: [16, 64] = 1024 параметра
        #   + bias: 64 параметра
        #   Итого: 1088 параметров
        #
        # Что делает этот слой:
        #   • Расширяет пространство признаков (с 16 до 64)
        #   • Каждый из 64 выходных признаков - взвешенная сумма 16 входных
        #   • Модель учится, какие комбинации входных признаков полезны
        self.linear_1 = nn.Linear(embed_dim, ff_dim)

        # ============================================================
        # ЛИНЕЙНЫЙ СЛОЙ 2 (W_2)
        # ============================================================
        # Математика: Output = ReLU(Intermediate) @ W_2
        #             W_2 имеет размер [ff_dim, embed_dim]
        #
        # Пример для embed_dim=16, ff_dim=64:
        #   W_2: [64, 16] = 1024 параметра
        #   + bias: 16 параметров
        #   Итого: 1040 параметров
        #
        # Что делает этот слой:
        #   • Сжимает пространство признаков (с 64 до 16)
        #   • Выделяет самое важное из расширенного представления
        #   • Возвращает размерность для следующего слоя трансформера
        self.linear_2 = nn.Linear(ff_dim, embed_dim)

        # Инициализация весов (как в главе 5)
        self._init_weights()

    def _init_weights(self):
        """
        Инициализация весов нормальным распределением.

        Это важно для стабильности обучения:
        • mean=0.0 - веса вокруг нуля (нет смещения в какую-либо сторону)
        • std=0.02 - маленькие значения (предотвращает взрыв градиентов)

        В реальном обучении:
        • Перед обучением: веса случайные (эти значения)
        • После обучения: веса оптимальные (модель выучила)
        • В математическом примере: мы использовали «красивые» числа
          (0.5, 0.3, 0.7) для удобства ручных вычислений
        """
        for module in [self.linear_1, self.linear_2]:
            nn.init.normal_(module.weight, mean=0.0, std=0.02)
            # Инициализируем bias нулями
            if module.bias is not None:
                nn.init.zeros_(module.bias)

    def forward(self, x):
        """
        Вычисляет Feed-Forward Network.

        Это главный метод, который реализует всю математику из главы 6.

        Args:
            x: входной тензор формы [batch_size, seq_length, embed_dim]
               или [seq_length, embed_dim] если нет батча
               Пример: [2, 10, 16] (2 примера, 10 токенов, 16 измерений)
               ← Это выход от Multi-Head Attention!

        Returns:
            output: выходной тензор формы [batch_size, seq_length, embed_dim]
                    Пример: [2, 10, 16] (такая же форма, как на входе!)

        Шаги (как в математической части главы 6):
          1. Linear 1: X @ W_1 → Intermediate [batch, seq, ff_dim]
          2. ReLU: max(0, x) → After ReLU [batch, seq, ff_dim]
          3. Linear 2: ReLU @ W_2 → Output [batch, seq, embed_dim]

        Важно: Каждый токен обрабатывается НЕЗАВИСИМО!
          • В Multi-Head Attention токены «общались» друг с другом
          • В FFN каждый токен обрабатывается отдельно
          • Это как после совещания (Attention) каждый сотрудник
            самостоятельно обдумывает полученную информацию (FFN)
        """
        # ============================================================
        # ПОДГОТОВКА: Обрабатываем вход без батча
        # ============================================================
        # Если вход без батча (например, [10, 16]), добавляем измерение батча
        # Это нужно для единообразия вычислений
        if x.dim() == 2:
            x = x.unsqueeze(0)  # [seq_len, embed_dim] → [1, seq_len, embed_dim]
            squeeze_output = True  # Запоминаем, что нужно убрать батч в конце
        else:
            squeeze_output = False

        batch_size, seq_length, embed_dim = x.shape
        # Пример: batch_size=2, seq_length=10, embed_dim=16

        # ============================================================
        # ШАГ 1: Linear 1 (W_1) - Расширение пространства
        # ============================================================
        # Математика: Intermediate = X @ W_1
        #             [batch, seq, embed] @ [embed, ff] = [batch, seq, ff]
        #
        # Пример: [2, 10, 16] → [2, 10, 64]
        #
        # Что происходит:
        #   • Каждый токен (16 чисел) проецируется в 64 числа
        #   • 64 промежуточных признака - это «развёрнутый анализ» токена
        #   • Модель учится, какие комбинации входных признаков полезны
        #
        # Аналогия:
        #   Было: краткая идея (16 чисел)
        #   Стало: подробный анализ с деталями (64 числа)

        intermediate = self.linear_1(x)
        # intermediate: [batch, seq_length, ff_dim]
        # Пример: [2, 10, 64]

        # ============================================================
        # ШАГ 2: ReLU - Функция активации (нелинейность)
        # ============================================================
        # Математика: ReLU(x) = max(0, x)
        #
        # Что происходит:
        #   • Все отрицательные значения становятся 0
        #   • Положительные остаются без изменений
        #
        # Пример:
        #   До ReLU:  [0.5, -0.3, 0.8, -0.1, 0.2]
        #   После:    [0.5,  0.0, 0.8,  0.0, 0.2]
        #
        # Зачем это нужно:
        #   1. Добавляет нелинейность (без этого два линейных слоя
        #      были бы эквивалентны одному линейному слою)
        #   2. Создаёт разреженность (около 50% нейронов «выключаются»)
        #   3. Улучшает градиенты для обратного распространения
        #
        # В нашем математическом примере все значения были положительными,
        # поэтому ReLU ничего не менял. В реальной модели около половины
        # значений будут отрицательными и обнулятся!

        activated = F.relu(intermediate)
        # activated: [batch, seq_length, ff_dim]
        # Пример: [2, 10, 64] (такая же форма, но некоторые значения = 0)

        # ============================================================
        # ШАГ 3: Linear 2 (W_2) - Сжатие пространства
        # ============================================================
        # Математика: Output = ReLU(Intermediate) @ W_2
        #             [batch, seq, ff] @ [ff, embed] = [batch, seq, embed]
        #
        # Пример: [2, 10, 64] → [2, 10, 16]
        #
        # Что происходит:
        #   • 64 промежуточных признака проецируются обратно на 16
        #   • Модель учится выделять самое важное из расширенного представления
        #   • Размерность возвращается к embed_dim для следующего слоя
        #
        # Аналогия:
        #   Было: подробный анализ с деталями (64 числа)
        #   Стало: главная выжимка, обогащённая идея (16 чисел)
        #
        # Почему это важно:
        #   • Следующий блок трансформера ожидает embed_dim
        #   • Мы сохраняем архитектуру масштабируемой
        #   • Можно складывать (stacking) много блоков друг на друга

        output = self.linear_2(activated)
        # output: [batch, seq_length, embed_dim]
        # Пример: [2, 10, 16]

        # ============================================================
        # ЗАВЕРШЕНИЕ: Убираем измерение батча, если добавляли
        # ============================================================
        if squeeze_output:
            output = output.squeeze(0)

        return output

    def get_num_parameters(self):
        """
        Возвращает количество обучаемых параметров в этом слое.

        Полезно для понимания масштаба модели.

        Формула:
          Linear 1: embed_dim × ff_dim + ff_dim (bias)
          Linear 2: ff_dim × embed_dim + embed_dim (bias)
          Итого: 2 × embed_dim × ff_dim + embed_dim + ff_dim

        В нашем примере (embed_dim=16, ff_dim=64):
          W_1: 16 × 64 = 1024
          bias_1: 64
          W_2: 64 × 16 = 1024
          bias_2: 16
          Итого: 2128 параметров

        В GPT-3 (175B, embed_dim=12288, ff_dim=49152):
          Итого: ~1.2 миллиарда параметров (только в одном блоке FFN!)

        Сравнение с Multi-Head Attention:
          • Attention: 4 × embed_dim² параметров
          • FFN: 2 × embed_dim × ff_dim параметров
          • При ff_dim = 4×embed_dim, FFN имеет в 2 раза больше параметров!
        """
        return sum(p.numel() for p in self.parameters())
